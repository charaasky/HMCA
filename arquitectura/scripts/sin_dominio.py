"""sin_dominio.py — generic "ask for something with no declared domain" flow (path A).

This is THE correct entry point according to the architecture decision: there is NOT one file per
domain (pedir_cargador.py, pedir_parlante.py...). There is ONE generic flow that consumes
HCMA. When a request does not match any canonical domain:

  1. DETECTS the gap.
  2. The LLM (external, consuming HCMA) DRAFTS the candidate spec (autor=modelo) and decides
     WHICH contingent data to search (the search queries are generated by the LLM, not the code).
  3. Searches the web ONLY for what the LLM asked to search, and registers it as `fuente:` (table/citation),
     NEVER invented.
  4. Registers the candidate in HCMA UNVERIFIED (not canonical).
  5. Applies the gate: computes what is derivable if possible, declares the non-derivable boundary.

The developer writes NOTHING here about 'cargador', 'parlante' or any other domain: that is
produced by the LLM at runtime. This module only ORCHESTRATES.

Usage:
    PYTHONPATH=/home/charasky/Documentos/HMC/.deps \
      python3 arquitectura/scripts/sin_dominio.py "diseñame un cargador para una Lenovo L15 Gen 3"
"""
