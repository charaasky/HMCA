def dominio_canonico_registrado(m, pedido):
    """Does a canonical domain already exist that covers this request? (gap detection)."""
    # iterates canonical specs (human source) and checks whether their name appears in the request
    norm = pedido.lower()
    for k in m.keys("skill:"):
        if k.endswith(":spec"):
            f = m.current(k)
            if f is not None and f["verified"] and f["fuente"] in ("ingeniero", "usuario"):
                nombre = f["value"].get("nombre", "") if isinstance(f["value"], dict) else ""
                if nombre and nombre.lower() in norm:
                    return k
    return None


def resolver(pedido, m=None, usar_llm=True, buscar_web=True, max_queries=8):
    """Complete generic flow. Returns a dict with the system's honest decision."""
    if m is None:
        m = HCMAMemoriaSQLite(":memory:")
    out = {"pedido": pedido, "via": "sin_dominio"}

    # 1. gap detection
    existente = dominio_canonico_registrado(m, pedido)
    if existente is not None:
        out["estado"] = "dominio_existente"
        out["dominio"] = existente
        return out
    out["estado"] = "hueco_detectado"

    # 2. the LLM drafts the candidate and decides what to search
    spec = GDC.generar_spec_candidata(pedido, usar_llm=usar_llm)
    did, v = GDC.inscribir_candidata(m, spec)
    out["dominio_id"] = did
    out["candidata"] = {"autor": spec["autor"], "version": v, "nombre": spec["nombre"],
                        "inputs": spec.get("inputs", []),
                        "formulas": spec.get("formulas", []),
                        "fuentes_citadas": spec.get("fuentes_citadas", []),
                        "topologia_bloques": spec.get("topologia_bloques"),
                        "mecanismos": spec.get("mecanismos", {}),
                        "puntos_operacion": spec.get("puntos_operacion", {}),
                        "bom": spec.get("bom", {})}

    # 3. search ONLY the contingent data the LLM asked to search, as unverified EVIDENCE
    fuentes = []
    lookup_queries = spec.get("lookup_queries", []) if isinstance(spec, dict) else []
    if isinstance(lookup_queries, list) and buscar_web and _HAY_BUSQUEDA:
        for lq in lookup_queries[:max_queries]:
            if not isinstance(lq, dict):
                continue
            query = lq.get("query")
            input_name = lq.get("input", "dato")
            if not query:
                continue
            try:
                res = busqueda_web(query)
            except Exception as e:
                out["error_web"] = repr(e)
                continue
            hechos = res.get("hechos", {}) if isinstance(res, dict) else {}
            urls = [u.get("url", "") for u in res.get("fuentes", []) if isinstance(u, dict)]
            if not hechos:
                continue  # no data recovered, register nothing
            fuente_id = f"{did}:{input_name}"
            try:
                # unverified EVIDENCE (autor=modelo): the web is NOT a canonical oracle
                skill_lib.registrar_evidencia_web(m, fuente_id, query, urls, hechos)
            except Exception:
                pass
            fuentes.append({"input": input_name, "hechos": hechos,
                            "fuente_id": fuente_id, "urls": urls})
    out["fuentes"] = fuentes

    # 4. gate: the candidate stays unverified; it is not canonical
    # Block topology: if the LLM proposed a graph, we validate it DETERMINISTICALLY. If it passes,
    # the state is ASUMIDA (grade derivado_bajo_supuesto); if there is no graph or it fails, it stays
    # AUSENTE (formula_suelta). The LLM NEVER self-declares: to reach 'conectado' the
    # human signature on the graph is required.
    grado_topo, faltantes_topo = _grado_topologia(spec)

    # 4b. complete REAL grade via grado_general (closes the sub-report gap).
    #     Without a human signature the graph stays ASUMIDA -> grade 1 (derivado_bajo_supuesto);
    #     if the spec also brings mechanisms and puntos_operacion/bom, grado_general
    #     weighs them (but WITHOUT a signature it never passes 1). 'fabricable' stays out (physical).
    grado_gg = _grado_general_spec(spec)

    # 4c. PHYSICAL VERIFICATION (deterministic cross-check, I-SIM): connects the physics when
    #     the domain declares a topology with verifiable typed blocks (tanque_lc,
    #     oscilador_cristal). It is DERIVATION (not an oracle): confronts simulated observable vs
    #     target physical law. Detects a parameter hallucination (e.g. wrong crystal) that
    #     the deontic layer alone does not see.
    verificacion = _verificacion_fisica(spec, m)

    out["gate"] = {
        "es_canonico": GDC.es_canonico(m, did),
        "invariante_ok": GDC.invariante_sin_camino_modelo_a_autoritativo(m, did)[0],
        "sin_fuente_humana": _no_hay_fuente_verified_sin_humano(m),
        "grado_topologico": grado_topo,
        "faltantes_topologia": faltantes_topo,
        "grado_real": grado_gg["grado"],
        "escalon_real": grado_gg["escalon"],
        "falta_para_subir": grado_gg["falta_para_subir"],
        "verificacion_fisica": verificacion,
    }
    return out


def _grado_topologia(spec):
    """Topological grade of a candidate spec, depending on whether it brings a valid block graph.

    - with a valid (unsigned) graph -> topologia_bloques.grado_desde_bloques(grafo, firmada=False)
    - with no graph or an invalid graph -> AUSENTE (formula_suelta).
    """
    grafo = spec.get("topologia_bloques") if isinstance(spec, dict) else None
    if isinstance(grafo, dict) and grafo.get("bloques"):
        import topologia_bloques as TB
        return TB.grado_desde_bloques(grafo, firmada=False)
    return T.grado_entregable([T.AUSENTE])


def _grado_general_spec(spec):
    """Complete REAL grade of a candidate spec via grado_general (without human signature).

    Closes the sub-report: before, the PDF only looked at `_grado_topologia` (which stays at
    grade 1 by design, since there is no signature). Here we delegate to `grado_general.grado_general`
    to report the honest rung and EXACTLY what is missing to move up (signature -> conectado,
    mechanisms -> funcional, BOM+points -> realizable). WITHOUT a human signature the ceiling is 1
    (derivado_bajo_supuesto); this does NOT raise the grade, only makes it visible and honest.
    """
    if not isinstance(spec, dict):
        return {"grado": "formula_suelta", "escalon": 0,
                "falta_para_subir": ["spec no es dict"]}
    grafo = spec.get("topologia_bloques")
    mecanismos = spec.get("mecanismos")
    puntos_operacion = spec.get("puntos_operacion")
    bom = spec.get("bom")
    import grado_general as GG
    # without a signature: the graph stays ASUMIDA -> grade 1 (maximum without a human).
    # The extra data (mechanisms/bom) is passed anyway, but grado_general does NOT use it
    # to move above 1 without a signature; it stays documented and 'falta_para_subir' clarifies it.
    return GG.grado_general(grafo, firma=None, modelos=mecanismos,
                           puntos_operacion=puntos_operacion, bom=bom)


def _verificacion_fisica(spec, m):
    """Deterministic cross-check of the domain's physics, if the topology allows it.

    From the typed block graph, it discovers verification templates (tanque_lc,
    oscilador_cristal, …) via `verificador_fisico.plantillas_para_grafo` and runs the
    simulated-vs-physical-law check. It is NOT an oracle nor a source: it is DERIVATION (calculator, never a root).

    Returns {nombre: {coherente, simulada, analitica, error_rel}} or {} if there is no closed
    verifiable physics. It does not raise the grade by itself (raising still requires a human signature).
    """
    try:
        import verificador_fisico as VF
    except Exception:
        return {}
    grafo = spec.get("topologia_bloques") if isinstance(spec, dict) else None
    if not isinstance(grafo, dict) or not grafo.get("bloques"):
        return {}
    plantillas = VF.plantillas_para_grafo(grafo)
    if not plantillas:
        return {}
    out = {}
    for p in plantillas:
        v = VF.verificar(p)
        out[p.get("nombre")] = {
            "coherente": v.get("coherente"),
            "simulada": v.get("simulada"),
            "analitica": v.get("analitica"),
            "error_rel": v.get("error_rel"),
            "fuente": v.get("fuente_simulacion"),
        }
    return out


def _no_hay_fuente_verified_sin_humano(m):
    """Extended invariant (P0 Fable): no verified source without a human actor.

    Returns True if the invariant holds (correct), False if there is a verified source
    with a non-human source (violation). The human sources are ingeniero/usuario; 'tabla'
    no longer mints on its own (registrar_fuente degrades it).
    """
    for k in m.keys("fuente:"):
        f = m.current(k)
        if f is not None and f["verified"] and f["fuente"] not in ("ingeniero", "usuario"):
            return False
    return True


def _sane_latex(s):
    """Replaces Unicode characters that the UTF-8 inputenc does not map to preamble glyphs.

    The preamble (prototipo.PREAMBULO_TEX) handles accents/±/—/·/° via T1, but NOT the Unicode
    math signs (U+2212 −, U+2192 →, U+00D7 ×, U+221A √, etc.). We map them to safe
    ASCII before sending to LaTeX."""
    m = {
        "\u2212": "-",   # math minus
        "\u2192": "->",  # right arrow
        "\u2190": "<-",
        "\u00d7": "x",   # multiplication
        "\u00f7": "/",
        "\u221a": "sqrt",
        "\u2264": "<=",
        "\u2265": ">=",
        "\u00b7": ".",   # middle dot
        "\u2026": "...",
        "\u201c": "\"", "\u201d": "\"",
        "\u2018": "'", "\u2019": "'",
        "\u03a9": "ohm",  # uppercase omega (ohms)
        "\u03c9": "omega",
        "\u03bc": "u",    # mu (micro)
        "\u03a3": "Sigma",
        "\u00b2": "2",
        "\u00b3": "3",
        "\u03c0": "pi",
        "\u03b7": "eta",
        "\u03b8": "theta",
        "\u2260": "!=",
        "\u00b1": "+-",
        "\u2248": "~",
    }
    for k, v in m.items():
        s = s.replace(k, v)
    # final fallback: preserve Latin-1 (accents/ñ/¿/¡/±/°/· supported by T1+inputenc),
    # replace any other non-ASCII (Greek, math symbols, emojis) with '?'.
    def _ok(ch):
        o = ord(ch)
        # ASCII or Latin-1 (U+00C0..U+00FF: accents, ñ, Ñ, ¿, ¡; U+00A0..U+00BF: ± ° µ ·)
        return o < 128 or (0xA0 <= o <= 0xFF)
    s = "".join(ch if _ok(ch) else "?" for ch in s)
    return s


def generar_pdf(r, salida):
    """Renders a generic PDF of the `resolver` result (candidate + data + gate).

    Does NOT hardcode a domain: it shows what the LLM drafted (inputs, formulas), the
    contingent data searched (with their URLs), and the honesty gate. Reuses the LaTeX preamble
    from prototipo.py. Returns the PDF path (or None if the render fails).
    """
    try:
        from prototipo import PREAMBULO_TEX, esc_latex
    except Exception:
        return None

    c = r.get("candidata", {})
    fs = r.get("fuentes", [])
    gate = r.get("gate", {})

    cuerpo = []

    # 1. Specifications (candidate inputs)
    cuerpo.append("\\section*{1. Especificaciones (candidata)}\n")
    inputs_list = c.get("inputs", [])
    if inputs_list:
        cuerpo.append("\\begin{itemize}\n")
        for i in inputs_list:
            if isinstance(i, dict):
                q = esc_latex(_sane_latex(str(i.get("question", i.get("name", "")))))
                u = esc_latex(_sane_latex(str(i.get("unit", ""))))
                cuerpo.append(f"  \\item {q} ({u})\n")
        cuerpo.append("\\end{itemize}\n\n")
    else:
        cuerpo.append("Sin especificaciones declaradas.\n\n")

    # 2. Formulas (deducible, citations)
    cuerpo.append("\\section*{2. Fórmulas deducibles}\n")
    formulas_list = c.get("formulas", [])
    if formulas_list:
        cuerpo.append("\\begin{itemize}\n")
        for f in formulas_list:
            cuerpo.append(f"  \\item {esc_latex(_sane_latex(str(f)))}\n")
        cuerpo.append("\\end{itemize}\n\n")
    else:
        cuerpo.append("Sin fórmulas deducibles.\n\n")

    # 2b. Block topology (if the LLM proposed it) + automatic visual SCHEMATIC
    grafo = c.get("topologia_bloques")
    esquema_pdf_path = None
    if isinstance(grafo, dict) and grafo.get("bloques"):
        cuerpo.append("\\section*{2b. Topología de bloques (propuesta por el modelo)}")
        cuerpo.append("\\begin{itemize}\n")
        for b in grafo.get("bloques", []):
            if isinstance(b, dict):
                puertos = ", ".join(f"{p.get('id')}({p.get('dominio')})" for p in b.get("puertos", [])
                                     if isinstance(p, dict))
                cuerpo.append(f"  \\item \\textbf{{{esc_latex(str(b.get('id')))}}} "
                              f"[{esc_latex(_sane_latex(str(b.get('tipo',''))))}]: {esc_latex(_sane_latex(puertos))}\n")
        cuerpo.append("\\end{itemize}\n")
        cuerpo.append("Conexiones (nets):\\begin{itemize}\n")
        for n in grafo.get("nets", []):
            if isinstance(n, dict):
                conns = ", ".join(f"{x.get('bloque')}.{x.get('puerto')}" for x in n.get("conexiones", [])
                                   if isinstance(x, dict))
                cuerpo.append(f"  \\item {esc_latex(str(n.get('id')))}: {esc_latex(_sane_latex(conns))}\n")
        cuerpo.append("\\end{itemize}\n\n")

        # AUTOMATIC VISUAL SCHEMATIC + SHAPE CONTROL (Fable ruling):
        #   1. converts the graph to a netlist;
        #   2. VERIFIES the shape (symbol fidelity, connections to existing pins);
        #   3. if it PASSES -> renders and embeds;
        #   4. if it FAILS -> HONEST DEGRADATION: the schematic is omitted and
        #      "did not pass shape control" is recorded in the gate (a lying drawing is NOT delivered).
        try:
            import esquematico_svg as ESV
            import topologia_a_esquema as T2E
            import verificador_forma as VF
            netlist = T2E.grafo_a_netlist(grafo)
            if netlist and netlist.get("componentes"):
                veredicto = VF.verificar_forma(netlist)
                if veredicto["aprueba"]:
                    # base path of the tex (without extension) to name the schematic
                    base = os.path.splitext(salida)[0]
                    esq_svg = base + "_esquematico.svg"
                    esq_pdf = base + "_esquematico.pdf"
                    svg = ESV.render_svg(netlist, esq_svg, "Esquemático del diseño")
                    if svg:
                        esq_pdf_out = ESV.svg_a_pdf(svg, esq_pdf)
                        if esq_pdf_out:
                            esquema_pdf_path = esq_pdf_out
                            cuerpo.append("\\section*{2c. Esquemático del circuito}\n")
                            cuerpo.append("\\begin{center}\n")
                            cuerpo.append(f"  \\includegraphics[width=0.95\\textwidth]"
                                          f"{{{os.path.basename(esq_pdf_out)}}}\n")
                            cuerpo.append("\\end{center}\n")
                            cuerpo.append("\\textit{Esquemático derivado de la topología de bloques "
                                          "propuesta por el modelo. No es netlist SPICE real; es la "
                                          "conectividad declarada.}\n\n")
                else:
                    # HONEST DEGRADATION: the schematic did NOT pass shape control.
                    # It is not drawn (so as not to lie with fallback symbols); it is recorded.
                    cuerpo.append("\\section*{2c. Esquemático del circuito}\n")
                    cuerpo.append("\\textit{Esquemático OMITIDO: no pasó control de forma.}\n\\begin{itemize}\n")
                    for d in veredicto.get("defectos", [])[:6]:
                        cuerpo.append(f"  \\item {esc_latex(_sane_latex(str(d)))}\n")
                    cuerpo.append("\\end{itemize}\n\n")
                    # reflect in the gate that the schematic was omitted (it did not lie)
                    gate.setdefault("_esquematico_estado", "omitido_no_paso_forma")
        except Exception as e:
            # if the schematic cannot be drawn, do not break the PDF: it is omitted and continues as text
            cuerpo.append("\\textit{(esquemático no disponible: " +
                          esc_latex(_sane_latex(str(e))) + ")}\\n\\n")

    # 3. Contingent data searched by web (unverified evidence)
    cuerpo.append("\\section*{3. Datos contingentes (evidencia web, no verificada)}\n")
    if fs:
        cuerpo.append("\\begin{itemize}\n")
        for f in fs:
            inp = esc_latex(_sane_latex(str(f.get("input", ""))))
            hechos = esc_latex(_sane_latex(str(f.get("hechos", {}))))
            cuerpo.append(f"  \\item \\textbf{{{inp}}}: {hechos}\n")
            for u in f.get("urls", [])[:2]:
                cuerpo.append(f"    \\textit{{{esc_latex(_sane_latex(u))}}}\n")
        cuerpo.append("\\end{itemize}\n\n")
    else:
        cuerpo.append("Sin datos contingentes recuperados.\n\n")

    # 4. Cited sources
    cuerpo.append("\\section*{4. Fuentes citadas}\n")
    fuentes_citadas = c.get("fuentes_citadas", [])
    if fuentes_citadas:
        cuerpo.append("\\begin{itemize}\n")
        for s in fuentes_citadas:
            cuerpo.append(f"  \\item {esc_latex(_sane_latex(str(s)))}\n")
        cuerpo.append("\\end{itemize}\n\n")
    else:
        cuerpo.append("Sin fuentes citadas.\n\n")

    # 5. Honesty gate
    cuerpo.append("\\section*{5. Gate de honestidad}\n")
    cuerpo.append("\\begin{itemize}\n")
    cuerpo.append(f"  \\item Canónico? {esc_latex(str(gate.get('es_canonico')))}\n")
    cuerpo.append(f"  \\item Invariante sin camino modelo->autoritativo: "
                  f"{esc_latex(str(gate.get('invariante_ok')))}\n")
    cuerpo.append(f"  \\item Ninguna fuente verified sin humano: "
                  f"{esc_latex(str(gate.get('sin_fuente_humana')))}\n")
    cuerpo.append("\\end{itemize}\n")

    # 5b. Topology state: the LLM candidate does NOT have a declared circuit
    cuerpo.append("\\section*{5b. Estado de topología (¿fabricable?)}\n")
    cuerpo.append("\\begin{itemize}\n")
    # complete REAL grade (closing the sub-report gap): if the gate brings `grado_real`
    # from grado_general we use it; otherwise we fall back to the old topological grade.
    grado_real = gate.get("grado_real", gate.get("grado_topologico", "formula_suelta"))
    cuerpo.append(f"  \\item Grado real: {esc_latex(str(grado_real))}\n")
    fal = gate.get("falta_para_subir") or gate.get("faltantes_topologia") or \
        ["topología de conexiones no declarada (fórmulas sueltas)"]
    for f in fal:
        cuerpo.append(f"  \\item Falta: {esc_latex(_sane_latex(str(f)))}\n")
    cuerpo.append("  \\item Conclusión: el grado mostrado es el REAL y honesto. NO es "
                  "'listo para fabricar' salvo que el grado sea 'fabricable' (grado 5, que "
                  "exige evidencia física y NO lo produce el software). Para subir de grado "
                  "hace falta lo listado en 'Falta'.\n")
    cuerpo.append("\\end{itemize}\n")

    # 5c. Physical verification (deterministic cross-check, if the domain triggers it)
    verificacion = gate.get("verificacion_fisica")
    if verificacion:
        cuerpo.append("\\section*{5c. Verificación física (chequeo cruzado determinista)}\n")
        cuerpo.append("\\begin{itemize}\n")
        for nombre, v in verificacion.items():
            coh = "COHERENTE" if v.get("coherente") else "INCOHERENTE (físicamente inviable)"
            cuerpo.append(f"  \\item \\textbf{{{esc_latex(str(nombre))}}}: {coh} — "
                          f"simulado {esc_latex(_sane_latex(str(v.get('simulada'))))} vs "
                          f"analítico {esc_latex(_sane_latex(str(v.get('analitica'))))} "
                          f"(error {esc_latex(_sane_latex(str(v.get('error_rel'))))}, "
                          f"fuente {esc_latex(_sane_latex(str(v.get('fuente'))))})\n")
        cuerpo.append("  \\item Nota: esta verificación es DERIVACIÓN (calculadora), no fuente ni "
                      "oráculo. Confirma coherencia física de la estructura, no validez de datos "
                      "contingentes ni 'fabricable'.\n")
        cuerpo.append("\\end{itemize}\n")

    # 6. (optional) verified calculations, if the result brings them
    calculos = r.get("calculos")
    if calculos:
        cuerpo.append("\\section*{6. Cálculos verificados}\n")
        cuerpo.append("\\begin{itemize}\n")
        for k, v in calculos.items():
            cuerpo.append(f"  \\item {esc_latex(str(k))} = {esc_latex(_sane_latex(str(v)))}\n")
        cuerpo.append("\\end{itemize}\n")

    # 7. (optional) non-derivable boundary, if the result declares it
    frontera = r.get("frontera_no_derivable")
    if frontera:
        cuerpo.append("\\section*{7. Frontera no-derivable (se declara, no se calcula)}\n")
        cuerpo.append("\\begin{itemize}\n")
        for f in frontera:
            cuerpo.append(f"  \\item {esc_latex(_sane_latex(str(f)))}\n")
        cuerpo.append("\\end{itemize}\n")

    titulo = esc_latex(_sane_latex(r.get("pedido", "pedido sin dominio")))
    latex = (PREAMBULO_TEX.replace("<<TITULO>>", titulo)
             + "".join(cuerpo) + "\\end{document}\n")

    salida = os.path.abspath(salida)
    os.makedirs(os.path.dirname(salida), exist_ok=True)
    with open(salida, "w", encoding="utf-8") as f:
        f.write(latex)

    import subprocess
    for _ in range(2):
        subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
                        salida], cwd=os.path.dirname(salida), check=False)
    pdf = salida.replace(".tex", ".pdf")
    return pdf if os.path.exists(pdf) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pedido", nargs="+", help="el pedido del usuario")
    ap.add_argument("--sin-web", action="store_true", help="no buscar en web (solo candidata del LLM)")
    args = ap.parse_args()
    pedido = " ".join(args.pedido)

    # The LLM is MANDATORY: without it there are no formulas and no candidate to register.
    # (--sin-llm was removed: it was a dead path that produced empty formulas and crashed.)
    r = resolver(pedido, usar_llm=True, buscar_web=not args.sin_web)

    print("=" * 74)
    print(f"PEDIDO: {pedido}")
    print("=" * 74)
    print(f"\n[1] {r['estado']}")
    if r["estado"] == "dominio_existente":
        print(f"    dominio canónico ya registrado: {r['dominio']}")
        return 0

    print(f"\n[2] El LLM redactó la candidata (autor={r['candidata']['autor']}):")
    print(f"    dominio_id={r['dominio_id']}  nombre='{r['candidata']['nombre']}'")

    print(f"\n[3] Datos contingentes buscados por web ({len(r['fuentes'])}):")
    for f in r["fuentes"]:
        print(f"    - input '{f['input']}': {f['hechos']}")
        for u in f["urls"][:2]:
            print(f"        {u}")

    print(f"\n[4] Gate: ¿canónico? {r['gate']['es_canonico']}  "
          f"(invariante OK={r['gate']['invariante_ok']})")
    print(f"    sin fuente verified sin humano = {r['gate']['sin_fuente_humana']}")
    print(f"    grado REAL = {r['gate'].get('grado_real', 'n/d')} "
          f"(escalón {r['gate'].get('escalon_real', 'n/d')})")
    for f in r['gate'].get('falta_para_subir', []):
        print(f"      falta para subir: {f}")
    print("\n" + "=" * 74)
    print("El LLM (consumiendo HCMA) redactó el dominio, buscó lo contingente, y lo dejó")
    print("como candidatura autor=modelo. El HCMA no lo promueve sin humano.")

    # 5. generate generic PDF with a name derived from the domain (does not overwrite previous ones)
    nombre_seguro = _sanear_nombre_archivo(r.get("dominio_id") or "sin_dominio")
    out_tex = os.path.join(SCRIPTS, "..", "resultados", f"{nombre_seguro}.tex")
    pdf = generar_pdf(r, out_tex)
    print(f"\n[5] PDF generado: {pdf if pdf else 'FALLO'}")
    print("=" * 74)
    return 0


def _sanear_nombre_archivo(s):
    """Converts a dominio_id into a safe file name (only [a-z0-9_-])."""
    import re
    s = s.lower().strip()
    s = s.replace(" ", "_")
    s = re.sub(r"[^a-z0-9_-]+", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    return s or "sin_dominio"


