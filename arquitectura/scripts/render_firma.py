"""render_firma.py — LEGIBLE render of the intent for the human signature ceremony.

Fable ruling (fable_gate_egreso_fable.md §3 and §5): the signature gate proves that a human signed
those bytes, NOT that they understood them. The approval screen must be generated BY THE MONITOR from
the canonical intent, and must show:
  - the registerable domain HIGHLIGHTED,
  - the visible punycode,
  - the COMPLETE query,
  - without truncation (if it does not fit, it is not signed),
  - agent strings ESCAPED (no control/bidi).

This module produces that render. It is a PURE and TOTAL function of the canonical intent: the text the
human reads is exactly the object they are going to sign, without omitted or summarized fields.
"""
import sys
import os

SCRIPTS = os.path.dirname(os.path.abspath(__file__))
if SCRIPTS not in sys.path:
    sys.path.insert(0, SCRIPTS)
import intent_canonico as IC  # noqa: E402


def _escapar(s):
    """Shows a string escaping control/bidi/spaces, without truncation."""
    if not isinstance(s, str):
        s = str(s)
    out = []
    for ch in s:
        o = ord(ch)
        if 0x20 <= o <= 0x7E:
            out.append(ch)
        elif ch in "\n\t\r":
            out.append(repr(ch)[1:-1])
        else:
            out.append(f"\\u{o:04X}")
    return "".join(out)


def normalizar_intent(intent):
    """Validates and returns the canonical NORMALIZED intent (http or mcp).

    The signing ceremony must operate on the CANONICAL (normalized) intent, not the agent's raw
    one: so the render and the signature point to the SAME object, without fields the agent might
    have left out (e.g. query omitted => normalized to [])."""
    if not isinstance(intent, dict):
        raise IC.IntentInvalido("intent no es dict")
    tipo = intent.get("tipo")
    if tipo == "http":
        return IC.validar_http(intent)
    if tipo == "mcp":
        return IC.validar_mcp(intent)
    raise IC.IntentInvalido(f"tipo de intent desconocido: {tipo!r}")


def render_intent(intent):
    """Returns the readable text of the canonical intent (http or mcp). TOTAL, without truncation.

    Raises IC.IntentInvalido if the intent is not canonical (nothing is signed that cannot be
    rendered completely).
    """
    if not isinstance(intent, dict):
        raise IC.IntentInvalido("intent no es dict")
    tipo = intent.get("tipo")
    if tipo == "http":
        return _render_http(intent)
    if tipo == "mcp":
        return _render_mcp(intent)
    raise IC.IntentInvalido(f"tipo de intent desconocido: {tipo!r}")


def _render_http(intent):
    intent = IC.validar_http(intent)  # canonical (normalizes, rejects descriptive fields)
    lineas = []
    lineas.append("INTENTO DE EGRESO — HTTP")
    lineas.append(f"  Método : {intent['metodo']}")
    lineas.append(f"  Esquema: {intent['scheme']}")
    # registerable domain HIGHLIGHTED (and in punycode, already normalized by validar_http)
    host = intent["host"]
    lineas.append(f"  Host   : {host}   <== DOMINIO REGISTRABLE")
    lineas.append(f"  Puerta : {intent['puerto']}")
    lineas.append(f"  Path   : {_escapar(intent['path'])}")
    query = intent.get("query") or []
    if query:
        lineas.append("  Query  :")
        for q in query:
            lineas.append(f"    {_escapar(q['clave'])} = {_escapar(str(q['valor']))} "
                          f"({q['tipo']}, máx {q['max_len']})")
    else:
        lineas.append("  Query  : (ninguna)")
    return "\n".join(lineas)


def _render_mcp(intent):
    intent = IC.validar_mcp(intent)
    lineas = []
    lineas.append("INTENTO DE EGRESO — MCP")
    lineas.append(f"  Server : {_escapar(intent['server_id'])}")
    lineas.append(f"  Tool   : {_escapar(intent['tool'])}")
    lineas.append(f"  Schema : {intent['hash_schema']}")
    lineas.append("  Args   :")
    for k, v in sorted(intent["args"].items()):
        lineas.append(f"    {_escapar(k)} = {_escapar(json_repr(v))}")
    return "\n".join(lineas)


def json_repr(v):
    import json
    return json.dumps(v, ensure_ascii=False, sort_keys=True)


def render_ceremonia(clave_necesidad, tool_id, intent):
    """COMPLETE text of the signing ceremony: what is going to be signed, without summary or truncation.

    `tool_id` and `intent` are what enter the signed payload; the render is of the SAME object."""
    cab = [
        "=" * 60,
        "FIRMA HUMANA — confirme EXACTAMENTE lo que firma",
        "=" * 60,
        f"Necesidad : {_escapar(clave_necesidad)}",
        f"Tool      : {_escapar(tool_id)}",
        "",
        render_intent(intent),
        "",
        "(Este texto es el objeto completo que se firma. Sin campos ocultos.)",
        "=" * 60,
    ]
    return "\n".join(cab)


if __name__ == "__main__":
    # demo
    print(render_ceremonia("necesidad:abc123", "http", {
        "schema": 1, "tipo": "http", "metodo": "GET", "scheme": "https",
        "host": "example.org", "puerto": 443, "path": "/v1/data",
        "query": [{"clave": "q", "valor": "hola mundo", "tipo": "string", "max_len": 256}],
    }))
