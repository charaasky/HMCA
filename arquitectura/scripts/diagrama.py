def _layout_componentes(componentes):
    """Positions components in a 2-column grid, returning {ref: (x, y)} and the pin_map.

    Each component is drawn at a position (x, y) with `alto = max(3, len(pines)*0.5)`.
    The pins are distributed: odd/left, even/right (or halves). Returns pin positions
    for each (ref, pin) so the connections can be drawn.
    """
    import math
    n = len(componentes)
    cols = 2
    rows = math.ceil(n / cols)
    pos = {}
    pin_pos = {}
    for i, c in enumerate(componentes):
        col = i % cols
        row = i // cols
        x = col * 12.0
        y = -row * 10.0
        ref = c.get("ref", f"C{i}")
        pines = c.get("pines") or []
        pos[ref] = (x, y)
        n_pines = len(pines)
        # component height larger as it has more pins
        alto = max(2.5, n_pines * 0.45)
        c["_alto"] = alto
        c["_ancho"] = 5.0
        # distribute pins: left half, right half
        izquierda = pines[: (n_pines + 1) // 2]
        derecha = pines[(n_pines + 1) // 2:]
        # left pins
        for j, p in enumerate(izquierda):
            py = y + alto / 2 - (j + 1) * (alto / (len(izquierda) + 1))
            pin_pos[(ref, p)] = (x - c["_ancho"] / 2, py)
        # right pins
        for j, p in enumerate(derecha):
            py = y + alto / 2 - (j + 1) * (alto / (len(derecha) + 1))
            pin_pos[(ref, p)] = (x + c["_ancho"] / 2, py)
    return pos, pin_pos


def dibujar_esquematico(netlist, salida_pdf, titulo="Esquemático"):
    """Draws the netlist as an electrical schematic (components + pins + connections).

    Returns the PDF path or None. Deterministic and offline.
    """
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.patches import Rectangle
    except Exception:
        return None

    componentes = netlist.get("componentes") or []
    conexiones = netlist.get("conexiones") or []
    if not componentes:
        return None

    pos, pin_pos = _layout_componentes(componentes)

    # figure dimensions
    n = len(componentes)
    max_y = max((p[1] for p in pos.values()), default=0.0)
    min_y = min((p[1] for p in pos.values()), default=0.0)
    fig, ax = plt.subplots(figsize=(max(9, 12), max(6, abs(min_y - max_y) / 1.5 + 3)))
    ax.axis("off")
    ax.set_aspect("equal")

    # 1. draw connections first (underneath the components)
    for cx in conexiones:
        a = cx.get("de"); b = cx.get("a")
        if not a or not b:
            continue
        pa = pin_pos.get((a.get("ref"), a.get("pin")))
        pb = pin_pos.get((b.get("ref"), b.get("pin")))
        if pa is None or pb is None:
            continue
        ax.plot([pa[0], pb[0]], [pa[1], pb[1]], color="#0f766e", lw=1.1, zorder=1)

    # 2. draw components (rectangle with pins)
    for c in componentes:
        ref = c.get("ref", "?")
        nombre = c.get("nombre", "")
        x, y = pos[ref]
        w = c.get("_ancho", 5.0)
        h = c.get("_alto", 2.5)
        rect = Rectangle((x - w / 2, y - h / 2), w, h,
                         linewidth=1.3, edgecolor="#0f172a", facecolor="#f1f5f9", zorder=2)
        ax.add_patch(rect)
        etiqueta = f"{ref}\n{nombre}" if nombre else ref
        ax.text(x, y, etiqueta, ha="center", va="center", fontsize=7.5,
                color="#0f172a", zorder=3)
        # draw pins with their number
        for p in (c.get("pines") or []):
            pp = pin_pos.get((ref, p))
            if pp is None:
                continue
            # stub toward the edge + number
            lado = -1 if pp[0] < x else 1
            ax.plot([pp[0], x + lado * w / 2], [pp[1], pp[1]],
                    color="#334155", lw=0.8, zorder=2)
            ax.text(pp[0] - lado * 0.3, pp[1] + 0.25, str(p),
                    ha="center", va="bottom", fontsize=5.5, color="#0f172a", zorder=4)

    ax.set_title(titulo, fontsize=11, color="#0f172a", pad=10)
    os.makedirs(os.path.dirname(salida_pdf), exist_ok=True)
    fig.savefig(salida_pdf, format="pdf", bbox_inches="tight")
    plt.close(fig)
    return salida_pdf if os.path.exists(salida_pdf) else None


def dibujar(grafo, salida_pdf, titulo="Diagrama de bloques"):
    """Degradation: simple block diagram (only if there is NO netlist). Kept for
    compatibility. A real schematic uses `dibujar_esquematico`."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.patches import FancyBboxPatch
    except Exception:
        return None
    bloques = grafo.get("bloques", [])
    conexiones = grafo.get("conexiones", [])
    if not bloques:
        return None
    n = len(bloques)
    ids = [b["id"] for b in bloques]
    etiquetas = [b.get("etiqueta", b["id"]) for b in bloques]
    fig, ax = plt.subplots(figsize=(max(6, n * 2.6), 3.0))
    ax.set_xlim(-1, n * 2 + 1); ax.set_ylim(-2, 2); ax.axis("off")
    pos = {bid: (i * 2.0, 0.0) for i, bid in enumerate(ids)}
    for a, b in conexiones:
        if a in pos and b in pos:
            xa, ya = pos[a]; xb, yb = pos[b]
            ax.annotate("", xy=(xb - 0.55, yb), xytext=(xa + 0.55, ya),
                        arrowprops=dict(arrowstyle="->", color="#334155", lw=1.6))
    for bid, etq in zip(ids, etiquetas):
        x, y = pos[bid]
        box = FancyBboxPatch((x - 0.55, y - 0.42), 1.1, 0.85,
                             boxstyle="round,pad=0.08,rounding_size=0.15",
                             linewidth=1.4, edgecolor="#1e293b", facecolor="#e2e8f0", zorder=3)
        ax.add_patch(box)
        ax.text(x, y, etq, ha="center", va="center", fontsize=8.5, color="#0f172a", zorder=4)
    ax.set_title(titulo, fontsize=11, color="#0f172a", pad=10)
    os.makedirs(os.path.dirname(salida_pdf), exist_ok=True)
    fig.savefig(salida_pdf, format="pdf", bbox_inches="tight")
    plt.close(fig)
    return salida_pdf if os.path.exists(salida_pdf) else None


def esquema_a_grafo(esquema_texto):
    """Degradation: converts 'A -> B -> C' into a block graph. Only for when there is no netlist."""
    bloques, conexiones = [], []
    if not isinstance(esquema_texto, str):
        return {"bloques": [], "conexiones": []}
    partes = [p.strip() for p in esquema_texto.split("->") if p.strip()]
    if len(partes) < 2:
        return {"bloques": [{"id": "b0", "etiqueta": esquema_texto.strip()}], "conexiones": []}
    def _id(p, i):
        base = "".join(c.lower() for c in p if c.isalnum())[:12] or f"b{i}"
        return base
    for i, p in enumerate(partes):
        bid = _id(p, i)
        while bid in [b["id"] for b in bloques]:
            bid = bid + "_"
        bloques.append({"id": bid, "etiqueta": p})
    for i in range(len(bloques) - 1):
        conexiones.append([bloques[i]["id"], bloques[i + 1]["id"]])
    return {"bloques": bloques, "conexiones": conexiones}


