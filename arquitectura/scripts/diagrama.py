"""diagrama.py — draws a legible ELECTRICAL SCHEMATIC (not a box diagram) from a
STRUCTURED NETLIST, using matplotlib (offline, deterministic, no network).

A schematic is NOT "boxes with arrows": it is each COMPONENT with its numbered PINS on the
edges, and the CONNECTIONS drawn as pin-to-pin lines. That is what makes a circuit legible.

Input: a structured netlist (generated by the LLM as data, not as free `->` text):
    {
      "componentes": [
        {"ref": "U1", "nombre": "CD4060", "pines": [1,2,3,...,16]},
        {"ref": "X1", "nombre": "Cristal 32.768k", "pines": [1,2]},
        ...
      ],
      "conexiones": [
        {"de": {"ref": "U1", "pin": 10}, "a": {"ref": "X1", "pin": 1}},
        ...
      ]
    }

Each component is drawn as a rectangle with its `ref:nombre` and its pins distributed on the
edges (left/right, numbered). The connections are line segments joining the source pin to
the destination one. It is legible: you see which pin connects to which pin.

If there is NO structured netlist (only free text), it falls back to a simple block diagram as
degradation (it never lies: there is no schematic without a netlist).
"""
