"""circuito_parlante.py — physical topology + netlist of the SPEAKER (1-way SEALED box).

Separates the TOPOLOGY (how the speaker is connected) from the numeric SIZING, just like
`circuito_cvt.py` separates the CVT from its domain. The topology is the IMPLICIT ASSUMPTION of each
derivation (ATMS, Falkenhainer&Forbus): without it, the numbers are "loose formulas".

Topology of the complete 1-way speaker (SEALED):
    amplifier_signal ──(+)─── driver (Re, motor) ──(-)─── return
                              │
                              └── sealed enclosure (sealed Vb), rigid wall, 2-way terminal

Components of the ELECTRICAL MODEL (Thiele-Small analog, closed box):
  - Re      : DC resistance of the coil (ohm)      [contingent datum]
  - Le      : coil inductance (mH)          [contingent datum]
  - Qts,Qes,Qms, Fs, VAS, Sd, Xmax, Sens             [contingent datum]
The closed box ONLY needs Qts and VAS (besides Fs) to be defined in 1st order:
  Qtc = Qts * sqrt(VAS/Vb + 1)                        (overdamping factor)
  Fcb = Fs * sqrt(VAS/Vb + 1)                         (in-box resonance frequency)
  F3  = Fcb * sqrt((1/Qtc² - 2 + sqrt((1/Qtc² - 2)² + 4)) / 2)   (only valid for Qtc > 1/√2)
The model is LINEAR (small signal); it does NOT cover Xmax/maximum excursion or distortion from
motor saturation at high power => the mechanism-coverage gate REFUSES to assert
"SPL at maximum excursion" with this model.

This module ONLY builds graph + netlist; the numeric computation lives in `dimensionamiento_parlante.py`.
"""
import os
