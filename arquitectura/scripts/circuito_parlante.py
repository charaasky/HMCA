def diagrama_conexiones(inputs, Q):
    """Textual connection diagram (declared topology of the speaker)."""
    V = inputs.get("amplificador_V")
    P = inputs.get("potencia_W")
    db = Q.get("spl_1m_dB")
    return (
        "PARLANTE 1 VIA (CAJA CERRADA/SEALED) — topología de conexión\n"
        "+-----------------------------------------------------------\n"
        f"  Amplificador {P} W @ {V} V  ---(+)---  DRIVER  ---(-)--- retorno\n"
        f"                             bobina Re + Le (motor eléctrico)\n"
        f"                             Sd={Q.get('sd_cm2', '?')} cm2, Xmax={Q.get('xmax_mm', '?')} mm\n"
        f"                             |\n"
        f"                             +--- RECINTO SELLADO Vb={Q.get('vb_L', '?')} L (rígido)\n"
        f"                             |   terminal 2 vías (cajita)\n"
        "+-----------------------------------------------------------\n"
        f"SPL estimado a 1 m (1 W, eje): {db} dB\n"
        "NOTA: el recinto es CERRADO (sin puerto). Un bass-reflex agrega\n"
        "      un conducto + puerto y cambia el alineamiento; NO está cubierto\n"
        "      por este modelo (ver gate de topología)."
    )


def netlist_spice(inputs, Q):
    """Equivalent electrical netlist (small-signal analog) for verification.

    Models the driver as a series R-L (Re + Le) fed by the amplifier voltage.
    Serves to verify by simulation that the RMS CURRENT (P=VI) matches the theoretical one.
    It does NOT model the enclosure's acoustic impedance (that is another, non-electrical observable).
    """
    Re = float(Q.get("re_ohm", 0.0))
    Le = float(Q.get("le_mH", 0.0)) / 1000.0
    Vpico = float(inputs.get("amplificador_V", 0.0)) * 1.41421356237
    return (
        "Parlante 1 via - analogo electrico (driver R-L)\n"
        f"V1 n1 0 SIN(0 {Vpico:.3f} 1000)\n"
        f"R1 n1 n2 {Re}\n"
        f"L1 n2 0 {Le}\n"
        ".tran 1u 5m 0 1u\n"
        ".control\nset filetype=ascii\nrun\nwrite out.raw\nquit\n.endc\n.end\n"
    )


def topologia_estado():
    """Topology state of this speaker: ASSUMED (generated by code, not ratified)."""
